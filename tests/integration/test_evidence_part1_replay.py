"""Part 1's own replay and experiment coverage (013/FR-035, FR-036, FR-037, SC-009; research D23, D24), written
before the wiring it guards: a replay copies its source's planted tokens with their armed state and applies the
same echo check to every message it re-sends; each replayed turn's result is derived from whether that turn
produced ANY evidence item — never the canary alone — on both the single-turn branch and the adaptive graph; a
pre-feature source skips the planted checks and runs every other; and an experiment's two arms detect alike.

The two reply detectors land later (US1, US2), so the disarm-on-replay and detector-only cases here drive the
wiring with a stub checker that reports a disarm and a non-canary item on command; T019 and T024 re-test them
with the real detectors. No attack text: placeholder messages and marker strings only."""
