class SequencedJudge:
    def __init__(self, *results, configured=True, model="stub/judge"):
        self.model, self.configured = model, configured
        self._results = list(results)
        self.calls: list[dict] = []

    async def judge(self, *, attack, reply, conversation=None, timeout=None):
        self.calls.append({"attack": attack, "reply": reply, "conversation": conversation})
        result = self._results.pop(0) if len(self._results) > 1 else self._results[0]
        return ParsedVerdict(result, "reason", progress="progress", tokens=10)


def ok(reply="an ordinary reply"):
    return Outcome(ok=True, step="success", message="Connection works.", reply_text=reply, reply_truncated=False,
                  status_code=200)


def sender_returning(*outcomes, record=None):
    seq = list(outcomes)

    async def send(resolved, **kwargs):
        if record is not None:
            record.append(kwargs)
        return seq.pop(0) if len(seq) > 1 else seq[0]
    return send


def single_turn_source(store, target, *, planted: bool = True, disarmed_turn: int | None = None):
    """A finished, succeeded single-turn source; with `planted`, one override token row (the joined form)."""
    run_id = store.claim_run(target.id, prompt_text="<seed with a planted paragraph>", **CLAIM)
    if planted:
        store.add_planted_token(run_id, kind="override", token=JOINED, prompt_id="override_task", prompt_version="1")
        if disarmed_turn is not None:
            store.disarm_planted_token(run_id, "override", disarmed_turn)
    store.finish_run(run_id, verdict="succeeded", hard_evidence=True, reply_text="<reply>")
    return store.get_run(run_id)


def adaptive_source(store, target, messages: list[str], *, planted: bool = True, disarmed_turn: int | None = None):
    """A finished, succeeded adaptive source whose recorded turns carry `messages`, succeeding on the last one."""
    run_id = store.claim_run(target.id, prompt_text=messages[0], mode="adaptive", attacker_model="a/m",
                             turn_budget=6, token_budget=40000, time_limit_s=300, **CLAIM)
    if planted:
        store.add_planted_token(run_id, kind="override", token=JOINED, prompt_id="override_task", prompt_version="1")
        if disarmed_turn is not None:
            store.disarm_planted_token(run_id, "override", disarmed_turn)
    for position, message in enumerate(messages, start=1):
        store.add_turn(run_id, position=position, attacker_message=message, reply_text="<reply>",
                       judge_verdict="succeeded" if position == len(messages) else "failed")
    store.finish_run(run_id, verdict="succeeded", hard_evidence=False, judge_used=True, judge_model="j/m",
                     stopping_condition="succeeded", succeeded_turn=len(messages), turns_used=len(messages))
    return store.get_run(run_id), store.list_turns(run_id)


class StubChecker(EvidenceChecker):
    """Reports a non-canary item on the turns in `item_turns`, unless the token was disarmed first: `note_sent`
    disarms when a sent message contains JOINED (the wiring under test is that the replay calls it for every
    re-sent message and derives each turn's result from the items, not from the canary flag)."""

    def __init__(self, *, item_turns=(), canaries=()):
        super().__init__(canaries=canaries, family="direct_injection")
        self.item_turns = set(item_turns)
        self.sent: list[tuple[str, int]] = []
        self.disarmed_turn: int | None = None
        self.checked: list[int] = []

    def note_sent(self, text, turn):
        self.sent.append((text, turn))
        if self.disarmed_turn is None and JOINED in text:
            self.disarmed_turn = turn
            return True
        return False

    async def check_turn(self, turn, reply, remaining):
        self.checked.append(turn)
        items = []
        if turn in self.item_turns and self.disarmed_turn is None:
            items.append(EvidenceItem(kind="unsafe_executable_output", turn=turn, location="reply",
                                      owasp_category="LLM05: Improper Output Handling",
                                      detail="placeholder detail", pattern_name="placeholder_pattern",
                                      pattern_set_version="1"))
        return TurnEvidence(items=items, canary_hit=False, side_channel_status="not_configured",
                            checks=["canary", "instruction_override", "unsafe_executable_output"],
                            reason="Hard evidence confirmed the attack: unsafe executable output.")


def replay(store, source, source_turns, *, judge, sender, evidence=None):
    return asyncio.run(execute_replay(store, source=source, source_turns=source_turns, resolved=RESOLVED,
                                      mode="local", judge=judge, sender=sender, evidence=evidence, **REPLAY_CAPS))


# ---- the token copy keeps its armed state (FR-035) ----


def test_a_replay_copies_the_sources_planted_token_with_its_armed_state(store, target):  # FR-035
    armed = single_turn_source(store, target)
    run = replay(store, armed, [], judge=StubJudge(verdict="failed"), sender=sender_returning(ok()))
    copied = store.list_planted_tokens(run.id)
    assert len(copied) == 1 and copied[0].token == JOINED and copied[0].armed is True
    assert copied[0].prompt_id == "override_task" and copied[0].prompt_version == "1"
    assert store.list_planted_tokens(armed.id)[0].armed is True   # the source's own row is untouched


def test_a_source_disarmed_on_turn_k_leaves_the_replay_disarmed_from_turn_k(store, target):  # FR-035
    source, turns = adaptive_source(store, target, ["<turn 1>", "<turn 2>", "<turn 3>"], disarmed_turn=2)
    run = replay(store, source, turns, judge=StubJudge(verdict="failed"), sender=sender_returning(ok()))
    copied = store.list_planted_tokens(run.id)
    assert len(copied) == 1 and copied[0].armed is False and copied[0].disarmed_turn == 2


# ---- the echo check applies to every re-sent message (FR-012, FR-035) ----


def test_a_resent_message_carrying_the_joined_form_disarms_the_replay_at_that_turn_and_records_no_override_item(
        store, target):  # FR-012, FR-035, SC-009
    source, turns = adaptive_source(store, target, ["<turn 1>", DISARMING_MESSAGE, "<turn 3>"])
    checker = StubChecker(item_turns=(3,))   # would report on turn 3's reply, were the token still armed
    judge = StubJudge(verdict="failed")
    run = replay(store, source, turns, judge=judge, sender=sender_returning(ok()), evidence=checker)
    assert [turn for _, turn in checker.sent] == [1, 2, 3]            # note_sent for every re-sent message, in order
    assert [text for text, _ in checker.sent] == [t.attacker_message for t in turns]
    assert checker.disarmed_turn == 2                                  # disarmed where the source's message said so
    assert checker.checked == [1, 2, 3]                                # the other checks still ran on every reply
    assert store.list_evidence(run.id) == []                           # no item after the disarm
    assert run.verdict == "failed" and run.hard_evidence is False and run.replay_outcome == "fixed"


# ---- any evidence item scores still vulnerable, on both paths (FR-035, SC-009; research D23) ----


def test_a_single_turn_replay_confirmed_only_by_a_detector_item_is_still_vulnerable(store, target):  # FR-035, SC-009
    source = single_turn_source(store, target)
    checker = StubChecker(item_turns=(1,))
    judge = StubJudge(verdict="failed")   # would say fixed; it must not even be consulted
    run = replay(store, source, [], judge=judge, sender=sender_returning(ok()), evidence=checker)
    assert run.verdict == "succeeded" and run.hard_evidence is True and run.judge_used is False
    assert run.replay_outcome == "still_vulnerable"
    assert judge.calls == []
    items = store.list_evidence(run.id)
    assert [i.kind for i in items] == ["unsafe_executable_output"] and items[0].turn == 1
    assert items[0].pattern_name == "placeholder_pattern" and items[0].pattern_set_version == "1"
    assert checker.sent == [(source.prompt_text, 1)]


def test_an_adaptive_replay_confirmed_only_by_a_detector_item_is_still_vulnerable(store, target):  # FR-035, SC-009
    source, turns = adaptive_source(store, target, ["<turn 1>", "<turn 2>", "<turn 3>"])
    checker = StubChecker(item_turns=(2,))
    judge = SequencedJudge("failed", "failed", "failed")
    run = replay(store, source, turns, judge=judge, sender=sender_returning(ok()), evidence=checker)
    assert run.verdict == "succeeded" and run.hard_evidence is True and run.succeeded_turn == 2
    assert run.replay_outcome == "still_vulnerable" and run.turns_used == 2   # stopped at the confirming turn
    assert len(judge.calls) == 1                                               # judged turn 1 only
    items = store.list_evidence(run.id)
    assert [(i.kind, i.turn) for i in items] == [("unsafe_executable_output", 2)]
    assert checker.sent == [("<turn 1>", 1), ("<turn 2>", 2)]


def test_a_canary_still_confirms_a_replay_through_the_checker(store, target):  # FR-001, FR-005, FR-035
    store.set_canaries(target.id, ["KESTREL-CANARY-X"])
    source = single_turn_source(store, target, planted=False)
    run = replay(store, source, [], judge=StubJudge(verdict="failed"),
                 sender=sender_returning(ok("leak KESTREL-CANARY-X")))
    assert run.verdict == "succeeded" and run.hard_evidence is True and run.replay_outcome == "still_vulnerable"
    items = store.list_evidence(run.id)
    assert [(i.kind, i.detail, i.owasp_category) for i in items] == [
        ("canary_in_reply", "KESTREL-CANARY-X", "LLM01: Prompt Injection")]


# ---- a pre-feature source: no planted token, the planted checks are skipped, every other runs (FR-036) ----


def test_a_pre_feature_source_gives_the_replay_no_tokens_and_still_runs_the_other_checks(store, target,
                                                                                          monkeypatch):  # FR-036
    store.set_canaries(target.id, ["KESTREL-CANARY-X"])
    source = single_turn_source(store, target, planted=False)
    seen: list[dict] = []
    real = replay_module.build_checker

    def spying(**kwargs):
        seen.append(kwargs)
        return real(**kwargs)
    monkeypatch.setattr(replay_module, "build_checker", spying)
    run = replay(store, source, [], judge=StubJudge(verdict="failed"),
                 sender=sender_returning(ok("leak KESTREL-CANARY-X")))
    assert len(seen) == 1 and list(seen[0]["planted"]) == []           # nothing copied: nothing to verify against
    assert store.list_planted_tokens(run.id) == []
    assert run.hard_evidence is True and run.replay_outcome == "still_vulnerable"


# ---- an experiment's two arms detect identically (FR-037) ----


ARM_A = {"attacker_model": "m-a", "judge_model": "j", "use_prior_experience": False,
         "turn_cap": 6, "token_budget": 40000, "write_back": False}
ARM_B = {"attacker_model": "m-b", "judge_model": "j", "use_prior_experience": True,
         "turn_cap": 6, "token_budget": 40000, "write_back": True}


def test_both_experiment_arms_detect_evidence_identically(make_client):  # FR-037
    transport = httpx.MockTransport(lambda request: httpx.Response(200, json={"reply": "it said KESTREL-CANARY-7"}))
    client = make_client(transport=transport, library=fixture_library(), judge=StubJudge(verdict="failed"),
                         attacker=StubAttacker())
    store = client.app.state.store
    terms = client.get("/api/config").json()["terms"]["version"]
    target = store.create_target(name="HS", url="http://t/chat", method="POST", headers=[],
                                 body_template='{"message":"{{prompt}}"}', response_path="$.reply", terms_version=terms)
    store.set_canaries(target.id, ["KESTREL-CANARY-7"])
    created = client.post("/api/experiments", json={"target_id": target.id, "mode": "single_turn",
                                                    "families": ["system_prompt_leak"], "reps": 2,
                                                    "arm_a": ARM_A, "arm_b": ARM_B})
    assert created.status_code == 201, created.text
    status = await_experiment(client, created.json()["id"])
    assert status["status"] == "finished" and status["completed_runs"] == 4
    result = client.get(f"/api/experiments/{created.json()['id']}/result").json()
    for arm in result["arms"]:
        assert arm["confirmed"] == {"successes": 2, "n": 2, "rate": 1.0, "ci": arm["confirmed"]["ci"]}
        assert arm["suspected"]["successes"] == 0
    experiment = store.get_experiment(created.json()["id"])
    for arm in experiment.arms:
        for run in store.arm_runs(experiment.id, arm.id):
            assert run.hard_evidence is True and run.judge_used is False
            assert [i.kind for i in store.list_evidence(run.id)] == ["canary_in_reply"]
    assert result["comparison"]["confirmed"]["diff"] == 0.0
